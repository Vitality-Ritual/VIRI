# Copy the Winter Arc planner's wording from app.js into the database seed, so
# the emailed plan (send_winter_arc, supabase/033) says exactly what the page says.
#
#     ruby tools/arc-seed.rb            rewrite the SEED part of supabase/033-winter-arc-email.sql
#     ruby tools/arc-seed.rb --print    print only the seed SQL (to paste after a wording change)
#
# Needs nothing beyond macOS: Ruby and the JavaScriptCore shell.
require 'json'
require 'open3'
Encoding.default_external = Encoding::UTF_8

ROOT = File.expand_path('..', __dir__)
JSC  = '/System/Library/Frameworks/JavaScriptCore.framework/Versions/A/Helpers/jsc'
app  = File.read(File.join(ROOT, 'website', 'app.js'), encoding: 'UTF-8')
from = app.index('const ARC=(()=>{') or abort 'ARC block not found in app.js'
data_start = app.index('const AREAS=', from) or abort 'AREAS not found'
data_end   = app.index('const DAYS=', data_start) or abort 'DAYS not found'
js = app[data_start...data_end] + "\nprint(JSON.stringify({areas:AREAS,goals:GOALS}));\n"

out, err, st = Open3.capture3(JSC, '-e', js)
abort "jsc failed: #{err}" unless st.success?
d = JSON.parse(out)

q = ->(v) { v.nil? ? 'null' : "'" + v.to_s.gsub("'", "''") + "'" }
sql = +"begin;\n"
d['areas'].each_with_index do |(id, label, _desc), i|
  sql << "insert into public.arc_areas (id, label, sort) values (#{q[id]}, #{q[label]}, #{i}) on conflict (id) do update set label = excluded.label, sort = excluded.sort;\n"
end
sql << "delete from public.arc_goals;\n"
d['areas'].each do |(area, _l, _d)|
  d['goals'][area].each_with_index do |g, i|
    b = g['block'] || {}
    vals = [area, g['id'], g['label'], g['adj'], g['phrase'], g['workout'], g['daily'],
            b['day'], b['b'], b['i'], b['t'] ? 'true' : 'false',
            g['habit'][0], g['habit'][1], g['habit'][2], g['ms'][0], g['ms'][1], g['ms'][2], i]
    cols = vals.each_with_index.map { |v, k| [7, 10, 17].include?(k) ? (v.nil? ? 'null' : v.to_s) : q[v] }
    sql << "insert into public.arc_goals (area, id, label, adj, phrase, workout, daily, block_day, block_b, block_i, block_t, habit, gentle, ambitious, ms1, ms2, ms3, sort) values (#{cols.join(', ')});\n"
  end
end
sql << "commit;\n"

if ARGV.include?('--print')
  puts sql
else
  f = File.join(ROOT, 'supabase', '033-winter-arc-email.sql')
  s = File.read(f, encoding: 'UTF-8')
  marker = '-- SEED (generated by tools/arc-seed.rb from app.js; do not edit by hand)'
  i = s.index(marker) or abort 'SEED marker missing'
  File.write(f, s[0, i + marker.length] + "\n" + sql, encoding: 'UTF-8')
  puts "wrote #{d['goals'].values.sum(&:size)} goals in #{d['areas'].size} categories"
end
